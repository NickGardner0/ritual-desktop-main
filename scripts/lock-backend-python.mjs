#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const inputs = ["apps/backend/requirements.in", "apps/backend/requirements-dev.in"];
const output = join(root, "apps/backend/requirements.lock.txt");
const railwayOutput = join(root, "apps/backend/requirements.txt");
const pythonVersion = "3.12.12";
const uvVersion = "0.9.2";

function inputDigest() {
  const hash = createHash("sha256");
  for (const path of inputs) {
    hash.update(`${path}\0`);
    hash.update(readFileSync(join(root, path)));
    hash.update("\0");
  }
  return hash.digest("hex");
}

const actualUv = execFileSync("uv", ["--version"], { cwd: root, encoding: "utf8" })
  .trim()
  .match(/^uv\s+([^\s]+)/)?.[1];
if (actualUv !== uvVersion) {
  console.error(`Backend lock generation requires uv ${uvVersion}; found ${actualUv || "unknown"}.`);
  process.exit(1);
}

const temporaryDirectory = mkdtempSync(join(tmpdir(), "ritual-backend-lock-"));
const temporaryLock = join(temporaryDirectory, "requirements.lock.txt");
try {
  execFileSync("uv", [
    "pip", "compile", "apps/backend/requirements-dev.in",
    "--python-version", pythonVersion,
    "--universal",
    "--generate-hashes",
    "--no-emit-index-url",
    "--no-header",
    "--output-file", temporaryLock,
  ], { cwd: root, stdio: "pipe" });
  const generated = readFileSync(temporaryLock, "utf8");
  const metadata = [
    `# ritual-input-sha256: ${inputDigest()}`,
    `# ritual-python-version: ${pythonVersion}`,
    `# ritual-uv-version: ${uvVersion}`,
    "# Generated by: npm run backend:lock",
  ].join("\n");
  const resolvedRequirements = `${metadata}\n--require-hashes\n${generated}`;
  writeFileSync(output, resolvedRequirements);
  // Railpack's pip dependency layer copies requirements.txt in isolation, so a
  // nested `-r requirements.lock.txt` cannot see the adjacent lock. Keep the
  // production entrypoint as a byte-identical generated mirror of the lock.
  writeFileSync(railwayOutput, resolvedRequirements);
  console.log(
    `Wrote ${output.slice(root.length + 1)} and ${railwayOutput.slice(root.length + 1)} for Python ${pythonVersion}.`,
  );
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}
