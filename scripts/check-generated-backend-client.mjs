#!/usr/bin/env node
import { existsSync, readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const root = process.cwd();
const openapiPath = join(root, "apps/backend/openapi.json");
const clientPath = join(root, "apps/dashboard/lib/api/generated/backend-client.ts");
const generatorPath = join(root, "scripts/generate-backend-client.mjs");
const errors = [];

if (!existsSync(generatorPath)) {
  errors.push("Missing backend client generator script.");
}

let expectedHash = null;
if (!existsSync(openapiPath)) {
  errors.push("Missing exported backend OpenAPI schema.");
} else {
  const schema = JSON.parse(readFileSync(openapiPath, "utf8"));
  expectedHash = createHash("sha256").update(JSON.stringify(schema)).digest("hex").slice(0, 16);
}

if (!existsSync(clientPath)) {
  errors.push("Missing generated backend client.");
} else {
  const source = readFileSync(clientPath, "utf8");
  if (!source.includes("Generated by scripts/generate-backend-client.mjs")) {
    errors.push("Generated backend client header is missing.");
  }
  if (!source.includes("createBackendClient")) {
    errors.push("Generated backend client factory is missing.");
  }
  if (expectedHash && !source.includes(`OpenAPI hash: ${expectedHash}`)) {
    errors.push("Generated backend client is out of date with apps/backend/openapi.json.");
  }
}

if (errors.length) {
  console.error("Generated backend client check failed:");
  for (const error of errors) {
    console.error(`- ${error}`);
  }
  process.exit(1);
}

console.log("Generated backend client check passed.");
