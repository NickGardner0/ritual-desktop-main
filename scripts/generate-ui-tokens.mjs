async function replaceMarked(filePath, startMarker, endMarker, generated) {
  const current = await readFile(filePath, "utf8");
  const start = current.indexOf(startMarker);
  const end = current.indexOf(endMarker);
  if (start === -1 || end === -1 || end < start) throw new Error(`Missing generated markers in ${path.relative(repositoryRoot, filePath)}`);
  return `${current.slice(0, start)}${generated}${current.slice(end + endMarker.length)}`;
}

