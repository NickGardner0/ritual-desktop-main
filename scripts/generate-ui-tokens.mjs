function get(pathValue) {
  return pathValue.split(".").reduce((value, key) => value?.[key], tokens);
}

function resolve(value, seen = new Set()) {
  if (Array.isArray(value)) return value.map((item) => resolve(item, seen));
  if (typeof value !== "string") return value;
  const match = /^\{([^}]+)\}$/.exec(value);
  if (!match) return value;
  if (seen.has(match[1])) throw new Error(`Circular token reference: ${match[1]}`);
  const token = get(match[1]);
  if (!token || !("$value" in token)) throw new Error(`Missing token reference: ${match[1]}`);
  return resolve(token.$value, new Set([...seen, match[1]]));
}

function tokenValue(pathValue) {
  const token = get(pathValue);
  if (!token || !("$value" in token)) throw new Error(`Missing token: ${pathValue}`);
  return resolve(token.$value);
}

function cssBlock(selector, values, { colorScheme } = {}) {
  const declarations = Object.entries(values).map(([name, value]) => `  --${name}: ${value};`);
  if (colorScheme) declarations.unshift(`  color-scheme: ${colorScheme};`);
  return `${selector} {\n${declarations.join("\n")}\n}`;
}

