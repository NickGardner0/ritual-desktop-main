const stale = [];
for (const [filePath, expected] of outputs) {
  let current = null;
  try { current = await readFile(filePath, "utf8"); } catch {}
  if (current === expected) continue;
  if (checkOnly) stale.push(path.relative(repositoryRoot, filePath));
  else {
    await mkdir(path.dirname(filePath), { recursive: true });
    await writeFile(filePath, expected);
  }
}

if (stale.length > 0) {
  console.error(`Generated token artifacts are stale:\n${stale.map((file) => `- ${file}`).join("\n")}`);
  process.exitCode = 1;
} else {
  console.log(checkOnly ? "Token artifacts are current." : "Generated token artifacts.");
}
